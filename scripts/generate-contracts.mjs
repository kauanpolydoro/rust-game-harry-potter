import { readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const schemaPath = resolve(repositoryRoot, 'contracts/health.schema.json')
const outputPath = resolve(repositoryRoot, 'apps/web/src/contracts/health.generated.ts')
const schema = JSON.parse(await readFile(schemaPath, 'utf8'))
const statuses = schema.properties?.status?.enum

if (!Array.isArray(statuses) || statuses.some((status) => typeof status !== 'string')) {
  throw new TypeError('health.schema.json must define a string enum at properties.status.enum')
}

const generated = `// Generated by scripts/generate-contracts.mjs. Do not edit.\n\nexport const healthStatuses = ${JSON.stringify(statuses)} as const\n\nexport type HealthStatus = (typeof healthStatuses)[number]\n\nexport interface HealthResponse {\n  status: HealthStatus\n}\n`

if (process.argv.includes('--check')) {
  const existing = await readFile(outputPath, 'utf8').catch(() => '')
  if (existing !== generated) {
    console.error('Generated health contract is stale. Run: npm run generate:contracts')
    process.exitCode = 1
  }
} else {
  await writeFile(outputPath, generated)
}
