import { readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const healthSchemaPath = resolve(repositoryRoot, 'contracts/health.schema.json')
const healthOutputPath = resolve(repositoryRoot, 'apps/web/src/contracts/health.generated.ts')
const healthSchema = JSON.parse(await readFile(healthSchemaPath, 'utf8'))
const statuses = healthSchema.properties?.status?.enum

if (!Array.isArray(statuses) || statuses.some((status) => typeof status !== 'string')) {
  throw new TypeError('health.schema.json must define a string enum at properties.status.enum')
}

const generatedHealth = `// Generated by scripts/generate-contracts.mjs. Do not edit.\n\nexport const healthStatuses = ${JSON.stringify(statuses)} as const\n\nexport type HealthStatus = (typeof healthStatuses)[number]\n\nexport interface HealthResponse {\n  status: HealthStatus\n}\n`

const identitySchemaPath = resolve(repositoryRoot, 'contracts/identity-access.schema.json')
const identityOutputPath = resolve(
  repositoryRoot,
  'apps/web/src/contracts/identity-access.generated.ts',
)
const identitySchema = JSON.parse(await readFile(identitySchemaPath, 'utf8'))
const openRoomStatuses = identitySchema.$defs?.RoomSummary?.properties?.status?.enum
const participantRoles = identitySchema.$defs?.ParticipantSummary?.properties?.role?.enum
const heroIds = identitySchema.$defs?.HeroId?.enum

if (
  !Array.isArray(openRoomStatuses) ||
  openRoomStatuses.some((status) => typeof status !== 'string') ||
  !Array.isArray(participantRoles) ||
  participantRoles.some((role) => typeof role !== 'string') ||
  !Array.isArray(heroIds) ||
  heroIds.some((heroId) => typeof heroId !== 'string')
) {
  throw new TypeError(
    'identity-access.schema.json must define string enums for room status, participant role and hero ID',
  )
}

const enumAliases = new Map([
  [identitySchema.$defs.RoomSummary.properties.status, 'OpenRoomStatus'],
  [identitySchema.$defs.ParticipantSummary.properties.role, 'ParticipantRole'],
  [identitySchema.$defs.HeroId, 'HeroId'],
])

function typeScriptType(schema, indentationLevel) {
  if (Array.isArray(schema.oneOf) && schema.oneOf.length > 0) {
    return schema.oneOf
      .map((variant) => typeScriptType(variant, indentationLevel))
      .join(' | ')
  }
  const enumAlias = enumAliases.get(schema)
  if (enumAlias) {
    return enumAlias
  }
  if (typeof schema.$ref === 'string') {
    return schema.$ref.split('/').at(-1)
  }
  if (Array.isArray(schema.enum)) {
    return schema.enum.map((value) => JSON.stringify(value)).join(' | ')
  }
  if (schema.type === 'string') {
    return 'string'
  }
  if (schema.type === 'boolean') {
    return 'boolean'
  }
  if (schema.type === 'integer' || schema.type === 'number') {
    return 'number'
  }
  if (schema.type === 'array' && schema.items) {
    return `Array<${typeScriptType(schema.items, indentationLevel)}>`
  }
  if (schema.type === 'object') {
    const properties = Object.entries(schema.properties ?? {})
    if (properties.length === 0) {
      return 'Record<string, unknown>'
    }
    const required = new Set(schema.required ?? [])
    const fieldIndent = '  '.repeat(indentationLevel)
    const closingIndent = '  '.repeat(indentationLevel - 1)
    const fields = properties.map(
      ([name, property]) =>
        `${fieldIndent}${name}${required.has(name) ? '' : '?'}: ${typeScriptType(property, indentationLevel + 1)}`,
    )
    return `{\n${fields.join('\n')}\n${closingIndent}}`
  }

  throw new TypeError(`unsupported JSON Schema fragment: ${JSON.stringify(schema)}`)
}

function refinementValidationExpressions(schema, value) {
  const refinements = schema['x-refinements']
  if (refinements === undefined) {
    return []
  }
  if (
    !Array.isArray(refinements) ||
    refinements.some((refinement) => typeof refinement !== 'string') ||
    new Set(refinements).size !== refinements.length
  ) {
    throw new TypeError('x-refinements must be an array of unique strings')
  }

  return refinements.map((refinement) => {
    if (refinement === 'min_lte_max') {
      return `${value}["min"] <= ${value}["max"]`
    }
    if (refinement === 'max_lt_options_length') {
      return `${value}["max"] < ${value}["options"].length`
    }
    throw new TypeError(`unsupported x-refinement: ${refinement}`)
  })
}

function validationExpression(schema, value) {
  if (Object.hasOwn(schema, 'const')) {
    return `${value} === ${JSON.stringify(schema.const)}`
  }
  if (schema.if !== undefined) {
    if (
      typeof schema.if !== 'object' ||
      schema.if === null ||
      (schema.then !== undefined && (typeof schema.then !== 'object' || schema.then === null)) ||
      (schema.else !== undefined && (typeof schema.else !== 'object' || schema.else === null))
    ) {
      throw new TypeError('if, then and else must contain JSON Schema objects')
    }
    const condition = validationExpression(schema.if, value)
    const whenTrue = schema.then === undefined ? 'true' : validationExpression(schema.then, value)
    const whenFalse = schema.else === undefined ? 'true' : validationExpression(schema.else, value)
    return `((${condition}) ? (${whenTrue}) : (${whenFalse}))`
  }
  if (schema.not !== undefined) {
    if (typeof schema.not !== 'object' || schema.not === null) {
      throw new TypeError('not must contain a JSON Schema object')
    }
    return `!(${validationExpression(schema.not, value)})`
  }
  if (Array.isArray(schema.oneOf)) {
    if (schema.oneOf.length === 0) {
      throw new TypeError('JSON Schema oneOf must define at least one variant')
    }
    const variants = schema.oneOf.map(
      (variant) => `(${validationExpression(variant, value)})`,
    )
    return `[${variants.join(',')}].filter(Boolean).length === 1`
  }
  if (typeof schema.$ref === 'string') {
    const definitionName = schema.$ref.split('/').at(-1)
    if (!identitySchema.$defs[definitionName]) {
      throw new TypeError(`identity-access.schema.json references unknown definition ${definitionName}`)
    }
    return `is${definitionName}(${value})`
  }

  if (schema.type === 'string') {
    const checks = [`typeof ${value} === 'string'`]
    if (schema.format === 'uuid') {
      checks.push(`isUuid(${value})`)
    } else if (schema.format === 'date-time') {
      checks.push(`isRfc3339DateTime(${value})`)
    } else if (schema.format !== undefined) {
      throw new TypeError(`unsupported JSON Schema string format: ${schema.format}`)
    }
    if (typeof schema.minLength === 'number') {
      checks.push(`[...${value}].length >= ${schema.minLength}`)
    }
    if (typeof schema.maxLength === 'number') {
      checks.push(`[...${value}].length <= ${schema.maxLength}`)
    }
    if (typeof schema.pattern === 'string') {
      checks.push(`new RegExp(${JSON.stringify(schema.pattern)}).test(${value})`)
    }
    if (Array.isArray(schema.enum)) {
      checks.push(`(${schema.enum.map((entry) => `${value} === ${JSON.stringify(entry)}`).join(' || ')})`)
    }
    return checks.join(' && ')
  }
  if (schema.type === 'boolean') {
    const checks = [`typeof ${value} === 'boolean'`]
    if (Array.isArray(schema.enum)) {
      checks.push(`(${schema.enum.map((entry) => `${value} === ${JSON.stringify(entry)}`).join(' || ')})`)
    }
    return checks.join(' && ')
  }
  if (schema.type === 'integer') {
    const checks = [`typeof ${value} === 'number'`, `Number.isInteger(${value})`]
    if (typeof schema.minimum === 'number') {
      checks.push(`${value} >= ${schema.minimum}`)
    }
    if (typeof schema.maximum === 'number') {
      checks.push(`${value} <= ${schema.maximum}`)
    }
    if (Array.isArray(schema.enum)) {
      checks.push(`(${schema.enum.map((entry) => `${value} === ${JSON.stringify(entry)}`).join(' || ')})`)
    }
    return checks.join(' && ')
  }
  if (schema.type === 'number') {
    return `typeof ${value} === 'number' && Number.isFinite(${value})`
  }
  if (schema.type === 'array' && schema.items) {
    const checks = [
      `Array.isArray(${value})`,
      `${value}.every((entry) => ${validationExpression(schema.items, 'entry')})`,
    ]
    if (
      typeof schema.minItems === 'number' &&
      schema.minItems === schema.maxItems
    ) {
      checks.push(`${value}.length === ${schema.minItems}`)
    } else {
      if (typeof schema.minItems === 'number') {
        checks.push(`${value}.length >= ${schema.minItems}`)
      }
      if (typeof schema.maxItems === 'number') {
        checks.push(`${value}.length <= ${schema.maxItems}`)
      }
    }
    if (schema.uniqueItems === true) {
      checks.push(`hasUniqueItems(${value})`)
    }
    return checks.join(' && ')
  }
  if (
    schema.type === 'object' ||
    (schema.type === undefined &&
      (schema.properties !== undefined || schema.required !== undefined))
  ) {
    const properties = Object.entries(schema.properties ?? {})
    const required = new Set(schema.required ?? [])
    const checks = [`isRecord(${value})`]
    if (schema.additionalProperties === false) {
      checks.push(
        properties.length === 0
          ? `Object.keys(${value}).length === 0`
          : `Object.keys(${value}).every((key) => ${JSON.stringify(properties.map(([name]) => name))}.includes(key))`,
      )
    }
    for (const [name, property] of properties) {
      const propertyValue = `${value}[${JSON.stringify(name)}]`
      const propertyCheck = validationExpression(property, propertyValue)
      checks.push(
        required.has(name)
          ? propertyCheck
          : `(!Object.hasOwn(${value}, ${JSON.stringify(name)}) || (${propertyCheck}))`,
      )
    }
    for (const name of required) {
      if (!properties.some(([propertyName]) => propertyName === name)) {
        checks.push(`Object.hasOwn(${value}, ${JSON.stringify(name)})`)
      }
    }
    if (schema.allOf !== undefined) {
      if (!Array.isArray(schema.allOf)) {
        throw new TypeError('allOf must contain an array of JSON Schema objects')
      }
      checks.push(...schema.allOf.map((candidate) => validationExpression(candidate, value)))
    }
    checks.push(...refinementValidationExpressions(schema, value))
    return checks.join(' && ')
  }

  throw new TypeError(`unsupported JSON Schema fragment: ${JSON.stringify(schema)}`)
}

const generatedDefinitions = Object.entries(identitySchema.$defs)
  .filter(([name]) => name !== 'HeroId')
  .map(([name, schema]) => {
    if (Array.isArray(schema.oneOf)) {
      const variants = schema.oneOf
        .map((variant) => `  | ${typeScriptType(variant, 2)}`)
        .join('\n')
      return `export type ${name} =\n${variants}`
    }
    if (schema.type === 'object' && schema.properties) {
      if (Object.keys(schema.properties).length === 0) {
        return `export type ${name} = Record<string, never>`
      }
      return `export interface ${name} ${typeScriptType(schema, 1)}`
    }
    throw new TypeError(
      `identity-access.schema.json definition ${name} must be an object or oneOf union`,
    )
  })
const generatedGuards = Object.entries(identitySchema.$defs).map(
  ([name, schema]) =>
    `export function is${name}(value: unknown): value is ${name} {\n  return ${validationExpression(schema, 'value')}\n}`,
)

const generatedIdentity = `// Generated by scripts/generate-contracts.mjs. Do not edit.\n\nexport const openRoomStatuses = ${JSON.stringify(openRoomStatuses)} as const\nexport const participantRoles = ${JSON.stringify(participantRoles)} as const\nexport const heroIds = ${JSON.stringify(heroIds)} as const\n\nexport type OpenRoomStatus = (typeof openRoomStatuses)[number]\nexport type ParticipantRole = (typeof participantRoles)[number]\nexport type HeroId = (typeof heroIds)[number]\n\n${generatedDefinitions.join('\n\n')}\n\nfunction isRecord(value: unknown): value is Record<string, unknown> {\n  return typeof value === 'object' && value !== null && !Array.isArray(value)\n}\n\nfunction canonicalJsonValue(value: unknown): string {\n  if (Array.isArray(value)) {\n    return 'array:[' + value.map(canonicalJsonValue).join(',') + ']'\n  }\n  if (isRecord(value)) {\n    const entries = Object.keys(value)\n      .sort()\n      .map((key) => JSON.stringify(key) + ':' + canonicalJsonValue(value[key]))\n    return 'object:{' + entries.join(',') + '}'\n  }\n  return typeof value + ':' + JSON.stringify(value)\n}\n\nfunction hasUniqueItems(values: unknown[]): boolean {\n  return new Set(values.map(canonicalJsonValue)).size === values.length\n}\n\nfunction isUuid(value: string): boolean {\n  return /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(value)\n}\n\nfunction isRfc3339DateTime(value: string): boolean {\n  const match = /^(\\d{4})-(\\d{2})-(\\d{2})T(?:[01]\\d|2[0-3]):[0-5]\\d:[0-5]\\d(?:\\.\\d+)?(?:Z|[+-](?:[01]\\d|2[0-3]):[0-5]\\d)$/.exec(value)\n  if (!match) {\n    return false\n  }\n  const year = Number(match[1])\n  const month = Number(match[2])\n  const day = Number(match[3])\n  return month >= 1 && month <= 12 && day >= 1 && day <= new Date(Date.UTC(year, month, 0)).getUTCDate()\n}\n\n${generatedGuards.join('\n\n')}\n`

if (process.argv.includes('--check')) {
  const existingHealth = await readFile(healthOutputPath, 'utf8').catch(() => '')
  const existingIdentity = await readFile(identityOutputPath, 'utf8').catch(() => '')
  if (existingHealth !== generatedHealth || existingIdentity !== generatedIdentity) {
    console.error('Generated contracts are stale. Run: npm run generate:contracts')
    process.exitCode = 1
  }
} else {
  await Promise.all([
    writeFile(healthOutputPath, generatedHealth),
    writeFile(identityOutputPath, generatedIdentity),
  ])
}
