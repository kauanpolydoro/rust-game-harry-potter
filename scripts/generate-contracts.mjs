import { readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const healthSchemaPath = resolve(repositoryRoot, 'contracts/health.schema.json')
const healthOutputPath = resolve(repositoryRoot, 'apps/web/src/contracts/health.generated.ts')
const healthSchema = JSON.parse(await readFile(healthSchemaPath, 'utf8'))
const statuses = healthSchema.properties?.status?.enum

if (!Array.isArray(statuses) || statuses.some((status) => typeof status !== 'string')) {
  throw new TypeError('health.schema.json must define a string enum at properties.status.enum')
}

const generatedHealth = `// Generated by scripts/generate-contracts.mjs. Do not edit.\n\nexport const healthStatuses = ${JSON.stringify(statuses)} as const\n\nexport type HealthStatus = (typeof healthStatuses)[number]\n\nexport interface HealthResponse {\n  status: HealthStatus\n}\n`

const identitySchemaPath = resolve(repositoryRoot, 'contracts/identity-access.schema.json')
const identityOutputPath = resolve(
  repositoryRoot,
  'apps/web/src/contracts/identity-access.generated.ts',
)
const identitySchema = JSON.parse(await readFile(identitySchemaPath, 'utf8'))
const openRoomStatuses = identitySchema.$defs?.RoomSummary?.properties?.status?.enum
const participantRoles = identitySchema.$defs?.ParticipantSummary?.properties?.role?.enum

if (
  !Array.isArray(openRoomStatuses) ||
  openRoomStatuses.some((status) => typeof status !== 'string') ||
  !Array.isArray(participantRoles) ||
  participantRoles.some((role) => typeof role !== 'string')
) {
  throw new TypeError('identity-access.schema.json must define string enums for room status and role')
}

const enumAliases = new Map([
  [identitySchema.$defs.RoomSummary.properties.status, 'OpenRoomStatus'],
  [identitySchema.$defs.ParticipantSummary.properties.role, 'ParticipantRole'],
])

function typeScriptType(schema, indentationLevel) {
  const enumAlias = enumAliases.get(schema)
  if (enumAlias) {
    return enumAlias
  }
  if (typeof schema.$ref === 'string') {
    return schema.$ref.split('/').at(-1)
  }
  if (Array.isArray(schema.enum)) {
    return schema.enum.map((value) => JSON.stringify(value)).join(' | ')
  }
  if (schema.type === 'string') {
    return 'string'
  }
  if (schema.type === 'boolean') {
    return 'boolean'
  }
  if (schema.type === 'integer' || schema.type === 'number') {
    return 'number'
  }
  if (schema.type === 'array' && schema.items) {
    return `Array<${typeScriptType(schema.items, indentationLevel)}>`
  }
  if (schema.type === 'object') {
    const properties = Object.entries(schema.properties ?? {})
    if (properties.length === 0) {
      return 'Record<string, unknown>'
    }
    const required = new Set(schema.required ?? [])
    const fieldIndent = '  '.repeat(indentationLevel)
    const closingIndent = '  '.repeat(indentationLevel - 1)
    const fields = properties.map(
      ([name, property]) =>
        `${fieldIndent}${name}${required.has(name) ? '' : '?'}: ${typeScriptType(property, indentationLevel + 1)}`,
    )
    return `{\n${fields.join('\n')}\n${closingIndent}}`
  }

  throw new TypeError(`unsupported JSON Schema fragment: ${JSON.stringify(schema)}`)
}

const generatedDefinitions = Object.entries(identitySchema.$defs).map(([name, schema]) => {
  if (schema.type !== 'object' || !schema.properties) {
    throw new TypeError(`identity-access.schema.json definition ${name} must be an object`)
  }
  return `export interface ${name} ${typeScriptType(schema, 1)}`
})

const generatedIdentity = `// Generated by scripts/generate-contracts.mjs. Do not edit.\n\nexport const openRoomStatuses = ${JSON.stringify(openRoomStatuses)} as const\nexport const participantRoles = ${JSON.stringify(participantRoles)} as const\n\nexport type OpenRoomStatus = (typeof openRoomStatuses)[number]\nexport type ParticipantRole = (typeof participantRoles)[number]\n\n${generatedDefinitions.join('\n\n')}\n`

if (process.argv.includes('--check')) {
  const existingHealth = await readFile(healthOutputPath, 'utf8').catch(() => '')
  const existingIdentity = await readFile(identityOutputPath, 'utf8').catch(() => '')
  if (existingHealth !== generatedHealth || existingIdentity !== generatedIdentity) {
    console.error('Generated contracts are stale. Run: npm run generate:contracts')
    process.exitCode = 1
  }
} else {
  await Promise.all([
    writeFile(healthOutputPath, generatedHealth),
    writeFile(identityOutputPath, generatedIdentity),
  ])
}
