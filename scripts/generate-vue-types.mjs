import { createHash } from 'node:crypto'
import { readdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, relative, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

import { compileScript, parse } from '@vue/compiler-sfc'
import { ElementTypes, NodeTypes } from '@vue/compiler-dom'

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const sourceRoot = process.env.VUE_TYPECHECK_SOURCE_ROOT
  ? resolve(process.env.VUE_TYPECHECK_SOURCE_ROOT)
  : resolve(repositoryRoot, 'apps/web/src')

async function vueFilesUnder(directory) {
  const entries = await readdir(directory, { withFileTypes: true })
  const files = []

  for (const entry of entries) {
    if (entry.isDirectory() && entry.name.startsWith('.vue-typecheck-')) {
      continue
    }

    const path = resolve(directory, entry.name)
    if (entry.isDirectory()) {
      files.push(...(await vueFilesUnder(path)))
    } else if (entry.isFile() && entry.name.endsWith('.vue')) {
      files.push(path)
    }
  }

  return files.sort()
}

export function compileVueForTypecheck(source, filename) {
  const { descriptor, errors } = parse(source, { filename })
  if (errors.length > 0) {
    throw new AggregateError(errors, `Vue parsing failed for ${filename}`)
  }

  if (!descriptor.scriptSetup) {
    throw new Error(`${filename} must use <script setup> for strict generated type checks`)
  }

  if (!descriptor.template?.ast) {
    throw new Error(`${filename} must contain a template block for type checking`)
  }

  const templateContract = {
    describedBy: [],
    controlledBy: [],
    formReferences: [],
    ids: new Set(),
    labelledBy: [],
    typeAssertions: [],
  }
  validateTemplateContract(descriptor.template.ast, filename, templateContract)
  for (const reference of templateContract.labelledBy) {
    if (!templateContract.ids.has(reference)) {
      throw new Error(`${filename} references missing id ${reference} from aria-labelledby`)
    }
  }
  for (const reference of templateContract.describedBy) {
    if (!templateContract.ids.has(reference)) {
      throw new Error(`${filename} references missing id ${reference} from aria-describedby`)
    }
  }
  for (const reference of templateContract.formReferences) {
    if (!templateContract.ids.has(reference)) {
      throw new Error(`${filename} references missing form id ${reference}`)
    }
  }
  for (const reference of templateContract.controlledBy) {
    if (!templateContract.ids.has(reference)) {
      throw new Error(`${filename} references missing id ${reference} from aria-controls`)
    }
  }

  const id = createHash('sha256').update(filename).digest('hex').slice(0, 8)
  const compiled = compileScript(descriptor, {
    genDefaultAs: '__sfc__',
    id,
    inlineTemplate: true,
  })

  const untypedContext = 'return (_ctx: any,_cache: any) => {'
  if (!compiled.content.includes(untypedContext)) {
    throw new Error(`Vue did not emit the expected render context for ${filename}`)
  }

  const generatedAssertions = templateContract.typeAssertions
    .map((expression) => `void ((${expression}) satisfies boolean | 'true' | 'false')`)
    .join('\n')
  const typedContent = compiled.content.replace(
    untypedContext,
    `${generatedAssertions}\n\nreturn (_ctx: __VueTemplateContext,_cache: any) => {`,
  )

  return `/* oxlint-disable */\n// Generated by scripts/generate-vue-types.mjs. Do not edit.\n\nimport type { ComponentPublicInstance as __VueTemplateContext } from 'vue'\n\n${typedContent}\n\nexport default __sfc__\n`
}

const supportedDirectives = new Set(['bind', 'else', 'else-if', 'for', 'if', 'model', 'on'])
const supportedBindings = new Set([
  'aria-busy',
  'aria-disabled',
  'aria-invalid',
  'class',
  'disabled',
  'key',
  'readonly',
  'type',
  'value',
])
const supportedEvents = new Set(['click', 'submit'])
const supportedElements = new Set([
  'button',
  'dd',
  'details',
  'div',
  'dl',
  'dt',
  'footer',
  'form',
  'fieldset',
  'h1',
  'h2',
  'h3',
  'header',
  'input',
  'label',
  'legend',
  'li',
  'main',
  'ol',
  'output',
  'option',
  'p',
  'section',
  'select',
  'small',
  'span',
  'strong',
  'summary',
  'template',
])
const booleanishAriaAttributes = new Set([
  'aria-atomic',
  'aria-busy',
  'aria-disabled',
  'aria-hidden',
])
const enumeratedAriaAttributes = new Map([['aria-live', new Set(['assertive', 'off', 'polite'])]])
const inlineCall = /^[A-Za-z_$][\w$]*(?:\.[A-Za-z_$][\w$]*)*\([^;]*\)$/s
const validId = /^[A-Za-z][\w:.-]*$/

function validateTemplateContract(node, filename, contract) {
  if (node.type === NodeTypes.ELEMENT) {
    if (![ElementTypes.ELEMENT, ElementTypes.TEMPLATE].includes(node.tagType)) {
      throw new Error(
        `${filename} uses <${node.tag}>; child components and slots require the official TypeScript 7 Vue checker`,
      )
    }
    if (!supportedElements.has(node.tag)) {
      throw new Error(`${filename} uses unsupported native element <${node.tag}>`)
    }

    for (const property of node.props) {
      if (property.type === NodeTypes.ATTRIBUTE) {
        validateStaticAttribute(node.tag, property, filename, contract)
        continue
      }

      if (property.type !== NodeTypes.DIRECTIVE) {
        continue
      }

      if (!supportedDirectives.has(property.name)) {
        throw new Error(`${filename} uses unsupported directive v-${property.name}`)
      }

      if (property.name === 'bind') {
        const binding = property.arg?.isStatic ? property.arg.content : ''
        if (!supportedBindings.has(binding)) {
          throw new Error(`${filename} uses unsupported dynamic binding :${binding || '[dynamic]'}`)
        }
        if (binding.startsWith('aria-') || binding === 'disabled') {
          if (!property.exp?.content.trim()) {
            throw new Error(`${filename} binding :${binding} must have a typed value`)
          }
          contract.typeAssertions.push(property.exp.content.trim())
        }
      }

      if (property.name === 'on') {
        const event = property.arg?.isStatic ? property.arg.content : ''
        const expression = property.exp?.content.trim() ?? ''
        if (!supportedEvents.has(event)) {
          throw new Error(`${filename} uses unsupported event @${event || '[dynamic]'}`)
        }
        if (!inlineCall.test(expression) || expression.includes('$event')) {
          throw new Error(
            `${filename} event @${event} must call a typed handler inline without $event`,
          )
        }
      }
    }
  }

  for (const child of node.children ?? []) {
    validateTemplateContract(child, filename, contract)
  }
}

function validateStaticAttribute(tag, attribute, filename, contract) {
  const name = attribute.name.toLowerCase()
  const value = attribute.value?.content ?? ''

  if (name.startsWith('on')) {
    throw new Error(`${filename} uses forbidden static event attribute ${attribute.name}`)
  }
  if (name === 'class') {
    return
  }
  if (booleanishAriaAttributes.has(name)) {
    if (!['false', 'true'].includes(value)) {
      throw new Error(`${filename} uses invalid ${name} value ${value || '[empty]'}`)
    }
    return
  }
  if (enumeratedAriaAttributes.has(name)) {
    if (!enumeratedAriaAttributes.get(name).has(value)) {
      throw new Error(`${filename} uses invalid ${name} value ${value || '[empty]'}`)
    }
    return
  }
  if (name === 'aria-labelledby') {
    const references = value.split(/\s+/).filter(Boolean)
    if (references.length === 0 || references.some((reference) => !validId.test(reference))) {
      throw new Error(`${filename} uses invalid aria-labelledby value ${value || '[empty]'}`)
    }
    contract.labelledBy.push(...references)
    return
  }
  if (name === 'aria-describedby') {
    const references = value.split(/\s+/).filter(Boolean)
    if (references.length === 0 || references.some((reference) => !validId.test(reference))) {
      throw new Error(`${filename} uses invalid aria-describedby value ${value || '[empty]'}`)
    }
    contract.describedBy.push(...references)
    return
  }
  if (name === 'aria-controls') {
    if (!validId.test(value)) {
      throw new Error(`${filename} uses invalid aria-controls value ${value || '[empty]'}`)
    }
    contract.controlledBy.push(value)
    return
  }
  if (name === 'id') {
    if (!validId.test(value) || contract.ids.has(value)) {
      throw new Error(`${filename} uses invalid or duplicate id ${value || '[empty]'}`)
    }
    contract.ids.add(value)
    return
  }
  if (name === 'role') {
    if (!['alert', 'status'].includes(value)) {
      throw new Error(`${filename} uses unsupported role ${value || '[empty]'}`)
    }
    return
  }
  if (name === 'type' && tag === 'button' && ['button', 'submit'].includes(value)) {
    return
  }
  if (name === 'type' && tag === 'input' && ['password', 'radio', 'text'].includes(value)) {
    return
  }
  if (
    name === 'autocomplete' &&
    tag === 'input' &&
    ['new-password', 'nickname', 'off'].includes(value)
  ) {
    return
  }
  if (name === 'inputmode' && tag === 'input' && value === 'text') {
    return
  }
  if (name === 'pattern' && tag === 'input' && value.length > 0) {
    return
  }
  if (name === 'spellcheck' && tag === 'input' && ['false', 'true'].includes(value)) {
    return
  }
  if (['maxlength', 'minlength'].includes(name) && tag === 'input' && /^\d+$/.test(value)) {
    return
  }
  if (name === 'name' && tag === 'input' && validId.test(value)) {
    return
  }
  if (name === 'required' && tag === 'input' && value === '') {
    return
  }
  if (name === 'value' && tag === 'option') {
    return
  }
  if (name === 'disabled' && tag === 'option' && value === '') {
    return
  }
  if (name === 'tabindex' && value === '-1') {
    return
  }
  if (name === 'form' && tag === 'button' && validId.test(value)) {
    contract.formReferences.push(value)
    return
  }
  if (name === 'for' && tag === 'label' && validId.test(value)) {
    contract.controlledBy.push(value)
    return
  }

  throw new Error(`${filename} uses unsupported static attribute ${attribute.name} on <${tag}>`)
}

async function generate({ check }) {
  let stale = false

  for (const sourcePath of await vueFilesUnder(sourceRoot)) {
    const source = await readFile(sourcePath, 'utf8')
    const generated = compileVueForTypecheck(source, relative(repositoryRoot, sourcePath))
    const outputPath = `${sourcePath}.typecheck.generated.ts`

    if (check) {
      const existing = await readFile(outputPath, 'utf8').catch(() => '')
      if (existing !== generated) {
        console.error(`${relative(repositoryRoot, outputPath)} is stale`)
        stale = true
      }
    } else {
      await writeFile(outputPath, generated)
    }
  }

  if (stale) {
    process.exitCode = 1
  }
}

const invokedPath = process.argv[1] ? pathToFileURL(resolve(process.argv[1])).href : ''
if (import.meta.url === invokedPath) {
  await generate({ check: process.argv.includes('--check') })
}
